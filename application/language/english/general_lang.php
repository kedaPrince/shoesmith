function general_labels(&$lang, $module, $singular, $plural="") {

	//Set plural word if not set
	empty($plural) && $plural = $module;

	$lang[$module.'_singular_heading']                  = ucwords($singular);
	$lang[$module.'_heading']                           = ucwords($plural);
	$lang[$module.'_add_heading']                       = 'Add '.ucwords($singular);
	$lang[$module.'_edit_heading']                      = 'Edit '.ucwords($singular);
	$lang[$module.'_view_heading']                      = 'View '.ucwords($singular);
	$lang[$module.'_no_rows']                           = 'There are no '.$plural.' available.';
	$lang[$module.'_create_success_heading']            = ucwords($singular).' Successfully Added';
	$lang[$module.'_create_success_description']        = 'The '.$singular.' "{name}" has successfully been added.';
	$lang[$module.'_create_failed_heading']             = 'Failed to add '.ucwords($singular);
	$lang[$module.'_create_failed_description']         = 'Failed to add the '.$singular.' "{name}".';
	$lang[$module.'_update_success_heading']            = ucwords($singular).' Successfully Updated';
	$lang[$module.'_update_success_description']        = 'The '.$singular.' "{name}" has successfully been updated.';
	$lang[$module.'_update_failed_heading']             = 'Failed to update '.ucwords($singular);
	$lang[$module.'_update_failed_description']         = 'Failed to update the '.$singular.' "{name}".';
	$lang[$module.'_remove_success_heading']            = ucwords($singular).' Successfully Removed';
	$lang[$module.'_remove_success_description']        = 'The '.$singular.' "{name}" has successfully been removed.';
	$lang[$module.'_remove_failed_heading']             = 'Failed to remove '.ucwords($singular);
	$lang[$module.'_remove_failed_description']         = 'Failed to remove the '.$singular.' "{name}".';
	$lang[$module.'_enable_success_heading']            = ucwords($singular).' Successfully Enabled';
	$lang[$module.'_enable_success_description']        = 'The '.$singular.' "{name}" has successfully been enabled.';
	$lang[$module.'_enable_failed_heading']             = 'Failed to enable '.ucwords($singular);
	$lang[$module.'_enable_failed_description']         = 'Failed to enable the '.$singular.' "{name}".';
	$lang[$module.'_disable_success_heading']           = ucwords($singular).' Successfully Disabled';
	$lang[$module.'_disable_success_description']       = 'The '.$singular.' "{name}" has successfully been disabled.';
	$lang[$module.'_disable_failed_heading']            = 'Failed to disable '.ucwords($singular);
	$lang[$module.'_disable_failed_description']        = 'Failed to disable the '.$singular.' "{name}".';
}

function success_label(&$lang, $module, $singular, $actionPresent, $actionPast, $plural="") {
	$lang[$module.'_'.$actionPresent.'_success_heading']            = ucwords($singular).' Successfully '.ucwords($actionPast);
	$lang[$module.'_'.$actionPresent.'_success_description']        = 'The '.$singular.' "{name}" has successfully been '.$actionPast.'.';
}

function fail_label(&$lang, $module, $singular, $actionPresent, $actionPast, $plural="") {
	$lang[$module.'_'.$actionPresent.'_failed_heading']            = 'Failed to '.$actionPresent.' '.ucwords($singular);
	$lang[$module.'_'.$actionPresent.'_failed_description']        = 'Failed to '.$actionPresent.' the '.$singular.' "{name}".';
}

function action_label(&$lang, $module, $singular, $actionPresent, $actionPast, $plural="") {
	success_label($lang, $module, $singular, $actionPresent, $actionPast, $plural);
	fail_label($lang, $module, $singular, $actionPresent, $actionPast, $plural);
}